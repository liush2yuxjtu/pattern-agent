#!/usr/bin/env python3
"""Build only the public static site, with deterministic pattern downloads."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PATTERN = ROOT / 'patterns/straight-skirt-eu40'


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build(destination):
    destination = destination.resolve()
    if destination == ROOT or ROOT not in destination.parents:
        raise ValueError('Build output must be a subdirectory of the repository')
    if destination.exists():
        if not (destination / '.pattern-agent-build').exists():
            raise ValueError('Refusing to replace a directory without a build marker')
        shutil.rmtree(destination)
    shutil.copytree(ROOT/'web', destination)
    (destination/'.pattern-agent-build').write_text('Generated by scripts/build_pages.py\n')
    bundle = destination/'patterns/straight-skirt-eu40'
    bundle.mkdir(parents=True)
    for source in sorted(PATTERN.iterdir()):
        if source.is_file() and source.suffix in {'.pdf','.png','.svg','.dxf','.sloper','.slm','.slayout','.json','.jsonl','.py','.txt','.md'}:
            shutil.copy2(source,bundle/source.name)
    archive = bundle.with_suffix('.zip')
    with zipfile.ZipFile(archive,'w',compression=zipfile.ZIP_DEFLATED) as z:
        for source in sorted(bundle.iterdir()):
            info=zipfile.ZipInfo('straight-skirt-eu40/'+source.name,(1980,1,1,0,0,0))
            info.compress_type=zipfile.ZIP_DEFLATED
            info.external_attr=0o644 << 16
            z.writestr(info,source.read_bytes())
    (destination/'.nojekyll').touch()
    checksums={str(p.relative_to(destination)):sha256(p) for p in sorted(destination.rglob('*'))
               if p.is_file() and p.name != '.pattern-agent-build'}
    inputs={str(p.relative_to(ROOT)):sha256(p) for directory in [ROOT/'web',PATTERN]
            for p in sorted(directory.rglob('*')) if p.is_file() and '__pycache__' not in p.parts and 'work' not in p.relative_to(ROOT).parts}
    inputs['scripts/build_pages.py']=sha256(Path(__file__))
    source_hash=hashlib.sha256(json.dumps(inputs,sort_keys=True).encode()).hexdigest()
    commit=os.environ.get('GITHUB_SHA') or subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip()
    metadata={'commit':commit,'source_sha256':source_hash,'files':checksums}
    (destination/'build.json').write_text(json.dumps(metadata,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({'output':str(destination.relative_to(ROOT)),'commit':commit,
                      'source_sha256':source_hash,'files':len(checksums)},indent=2))
    return metadata


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=ROOT/'dist')
    build(parser.parse_args().output)
