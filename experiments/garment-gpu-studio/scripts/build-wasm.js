// A deliberately small, reproducible encoder for numeric f64 WebAssembly functions.
// No compiler, network, imports or JavaScript math fallback at runtime.
import fs from 'node:fs';
const u=n=>{const out=[];do{let b=n&127;n>>>=7;out.push(b|(n?128:0));}while(n);return out;};
const str=s=>[...u(Buffer.byteLength(s)),...Buffer.from(s)];
const num=n=>{const b=Buffer.alloc(8);b.writeDoubleLE(n);return [0x44,...b];};
const get=i=>[0x20,...u(i)];
const ops={add:0xa0,sub:0xa1,mul:0xa2,div:0xa3,min:0xa4,max:0xa5,sqrt:0x9f,abs:0x99};
const expr=e=>typeof e==='number'?num(e):e[0]==='arg'?get(e[1]):[...e.slice(1).flatMap(expr),ops[e[0]]];
const a=['arg',0],b=['arg',1],c=['arg',2],area=['arg',3];
const mul=(a,b)=>['mul',a,b],add=(a,b)=>['add',a,b],sub=(a,b)=>['sub',a,b],div=(a,b)=>['div',a,b];
const delta=sub(a,c),hi=mul(.5,add(add(a,c),['sqrt',add(mul(delta,delta),mul(4,mul(b,b)))]));
const functions=[
  {name:'principal_max',n:3,e:['sqrt',['max',0,hi]]},
  {name:'principal_min',n:4,e:['sqrt',['max',0,div(area,['max',1e-300,hi])]]},
  {name:'green_normal',n:1,e:mul(.5,sub(a,1))},
  {name:'plane_stress',n:4,e:mul(div(c,sub(1,mul(area,area))),add(a,mul(area,b)))},
  {name:'shear_stress',n:3,e:mul(div(b,add(1,c)),a)},
];
const sec=(id,bytes)=>[id,...u(bytes.length),...bytes];
const types=functions.flatMap(f=>[0x60,...u(f.n),...Array(f.n).fill(0x7c),1,0x7c]);
const bytes=new Uint8Array([0,97,115,109,1,0,0,0,...sec(1,[...u(functions.length),...types]),...sec(3,[...u(functions.length),...functions.flatMap((_,i)=>u(i))]),...sec(7,[...u(functions.length),...functions.flatMap((f,i)=>[...str(f.name),0,...u(i)])]),...sec(10,[...u(functions.length),...functions.flatMap(f=>{const body=[0,...expr(f.e),0x0b];return [...u(body.length),...body];})])]);
if(!WebAssembly.validate(bytes))throw new Error('Invalid numeric WASM');
const watExpr=e=>typeof e==='number'?'(f64.const '+e+')':e[0]==='arg'?'(local.get '+e[1]+')':'(f64.'+e[0]+' '+e.slice(1).map(watExpr).join(' ')+')';
fs.writeFileSync(new URL('../assets/strain-kernel.wat',import.meta.url),'(module\n'+functions.map(f=>'  (func (export \"'+f.name+'\") (param '+Array(f.n).fill('f64').join(' ')+') (result f64) '+watExpr(f.e)+')').join('\n')+'\n)\n');
fs.writeFileSync(new URL('../assets/strain.wasm',import.meta.url),bytes);
console.log(`WASM: ${bytes.length} bytes, five f64 functions`);

fs.writeFileSync(new URL('../src/wasm-binary.js',import.meta.url),'// Generated by scripts/build-wasm.js\nexport default new Uint8Array('+JSON.stringify(Array.from(bytes))+');\n');
