#!/usr/bin/env python3
"""Re-run artifact gates and require an explicit human decision for this revision."""

import argparse
from datetime import date
import hashlib
from importlib.util import module_from_spec, spec_from_file_location
import json
import math
from pathlib import Path
import sys


HERE = Path(__file__).resolve().parent
MIN_DIGITAL_GATES = 5
TOLERANCE_MM = 1.0
MARKS = ('design_matches_brief', 'cut_markings_readable', 'all_tile_joins_aligned')


def load_module(name, filename):
    spec = spec_from_file_location(name, HERE / filename)
    module = module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def fingerprint(trial):
    files = ['revision.json', *[f'outputs/revision/{name}' for name in ['pattern.dxf', 'full.pdf', 'a4.pdf']]]
    if any(not (trial / f).is_file() for f in files):
        return None
    hashes = {name: hashlib.sha256((trial / name).read_bytes()).hexdigest() for name in files}
    return {'fingerprint': hashlib.sha256(json.dumps(hashes, sort_keys=True).encode()).hexdigest(), 'files': hashes}


def decide(gates, subject, approval):
    passed = sum(gate['passed'] is True for gate in gates)
    if len({g['id'] for g in gates}) != len(gates) or passed < MIN_DIGITAL_GATES or passed != len(gates) or not subject:
        return 'DIGITAL_FAILED', '至少五个不同关口且本轮全部适用关口通过，才进入人工验收。'
    if approval is None:
        return 'AWAITING_HUMAN', '缺少对当前版的人工实际查验及明确签核。'
    if not isinstance(approval, dict):
        return 'HUMAN_EVIDENCE_INVALID', '人工回执格式错误。'
    if approval.get('fingerprint') != subject['fingerprint']:
        return 'HUMAN_EVIDENCE_INVALID', '回执版次与当前参数或文件摘要不匹配。'
    if not isinstance(approval.get('reviewer'), str) or not approval['reviewer'].strip():
        return 'HUMAN_EVIDENCE_INVALID', '缺检查人。'
    try:
        date.fromisoformat(approval['review_date'])
    except (ValueError, TypeError, KeyError):
        return 'HUMAN_EVIDENCE_INVALID', '缺有效复核日期。'
    if approval.get('decision') == 'reject':
        return 'HUMAN_REJECTED', '人工判定退回。沿原问题修复并重跑，再提交本版签核。'
    if approval.get('decision') != 'approve':
        return 'HUMAN_EVIDENCE_INVALID', '需要人工明确给出批准或退回。'
    measures = [approval.get('scale_x_mm'), approval.get('scale_y_mm')]
    if not all(type(v) in (int, float) and math.isfinite(v) and abs(v - 100) <= TOLERANCE_MM for v in measures):
        return 'HUMAN_EVIDENCE_INVALID', '同版实际大小试印的校准方框须记录横纵两边，均在一百毫米的允许偏差内。'
    if approval.get('actual_size_printed') is not True or any(approval.get(mark) is not True for mark in MARKS):
        return 'HUMAN_EVIDENCE_INVALID', '缺少实体试印、设计意图、裁剪标记或完整拼接的人工通过记录。'
    return 'APPROVED', '数字关口与该版人工终审均通过，可交付为可打印打样纸样。'


def load_approvals(path):
    if path is None:
        return {}
    records = json.loads(path.read_text(encoding='utf-8'))
    if not isinstance(records, dict):
        raise ValueError('Approvals must be an object keyed by case ID and configuration, such as 33/with_skill.')
    return records


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('workspace', type=Path)
    parser.add_argument('report', type=Path)
    parser.add_argument('--approvals', type=Path, help='Human-supplied decision records. Never generated by the runner.')
    parser.add_argument('--audit-recorded-exports', action='store_true', help='Reassemble the known PDF encodings from the archived four baseline runs.')
    args = parser.parse_args()
    root = args.workspace.resolve()
    approvals = load_approvals(args.approvals)
    grader = load_module('draft_grader', 'grade-zero-draft.py')
    tile_rows, audit_error = [], None
    if args.audit_recorded_exports:
        try:
            tile_audit = load_module('recorded_tile_audit', 'audit-recorded-tile-vectors.py')
            tile_rows = tile_audit.audit(root)['runs']
        except (OSError, ValueError, RuntimeError) as exc:
            audit_error = str(exc)
    results = {}
    for case in grader.CASES:
        for config in ['with_skill', 'old_skill']:
            key = f'{case["id"]}/{config}'
            trial = root / f'eval-{case["id"]}-{case["name"]}' / config
            before = fingerprint(trial)
            evidence = grader.grade(trial, case, repeats=3)
            subject = fingerprint(trial)
            gates = [{'id': f'G{i}', 'name': check['text'], 'passed': check['passed'], 'evidence': check['evidence']}
                     for i, check in enumerate(evidence['expectations'], 1)]
            if before != subject:
                gates.append({'id': 'STABILITY', 'name': '验收期间版次一致', 'passed': False, 'evidence': '验收期间文件内容改变。'})
            if args.audit_recorded_exports:
                rows = [row for row in tile_rows if row['case'] == case['id'] and row['configuration'] == config]
                valid = {row['variant'] for row in rows} == {'base', 'revision'} and all(row['passed'] for row in rows)
                counts = []
                for row in rows:
                    detail = row.get('error') or f'{row["adjacent_pairs_matched"]}/{row["adjacent_pairs_total"]} 个相邻拼接位置'
                    counts.append(f'{row["variant"]}: {detail}')
                gates.append({'id': 'G8', 'name': '拼页重组后独立核对净线、裁剪线与标记', 'passed': valid,
                              'evidence': audit_error or '；'.join(counts) or '没有匹配的重组结果。'})
            verdict, reason = decide(gates, subject, approvals.get(key))
            human_status = {'APPROVED': 'PASS', 'AWAITING_HUMAN': 'PENDING', 'DIGITAL_FAILED': 'BLOCKED'}.get(verdict, 'FAIL')
            results[key] = {'case': case['name'], 'subject': subject, 'digital_gates': gates,
                            'rebuild_seconds': evidence['rebuild_seconds'],
                            'human_gate': {'id': 'H1', 'status': human_status, 'reason': reason, 'receipt': approvals.get(key)},
                            'overall': verdict, 'ready': verdict == 'APPROVED'}
            print(f'{key} {sum(g["passed"] for g in gates)}/{len(gates)} {verdict}', flush=True)
    args.report.write_text(json.dumps({'minimum_digital_gates': MIN_DIGITAL_GATES,
                                       'physical_scale_tolerance_mm': TOLERANCE_MM, 'runs': results},
                                      ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    final = [row['overall'] for key, row in results.items() if key.endswith('/with_skill')]
    if any(state not in {'APPROVED', 'AWAITING_HUMAN'} for state in final):
        return 1
    return 0 if all(state == 'APPROVED' for state in final) else 2


if __name__ == '__main__':
    raise SystemExit(main())
